def generate_tests_with_llm(client, spec_path, prefix,
                             pipeline_label, output_path,
                             include_notes=False):
    print(f"\n[{pipeline_label.upper()}] Generating {os.path.basename(output_path)} …")

    reqs = parse_requirements_from_spec(spec_path)
    valid_requirement_ids = {req["id"] for req in reqs}

    if not reqs:
        print(f"  ERROR: No requirements parsed from {spec_path}. "
              f"Run 06_spec_generate.py first.")
        return

    if os.path.exists(output_path):
        print(f"  File already exists — skipping LLM generation.")
        with open(output_path, "r", encoding="utf-8") as f:
            data = json.load(f)
        errors = validate_tests(data.get("tests", []), pipeline_label, valid_requirement_ids)
        if not errors:
            return
        print("  Regenerating file to match the current spec and required test format.")

    all_tests = []

    for i, req in enumerate(reqs, start=1):
        test_id = f"T_{prefix}_{i}"
        notes_instruction = (
            "Also include a 'notes' field (one sentence explaining what was "
            "refined or why this test was written this way)."
            if include_notes else
            "Do NOT include a 'notes' field."
        )

        prompt = f"""You are a QA engineer writing a structured test case for the
Headspace meditation app.

Requirement ID : {req['id']}
Description    : {req['description']}
Acceptance     : {req['acceptance']}
Source Persona : {req['persona']}

Write ONE test case for this requirement.
{notes_instruction}

Return ONLY valid JSON — no markdown fences, no explanation.

Use this exact schema:
{{
  "test_id": "{test_id}",
  "requirement_id": "{req['id']}",
  "scenario": "<short descriptive scenario name>",
  "steps": [
    "<step 1>",
    "<step 2>",
    "<step 3>"
  ],
  "expected_result": "<measurable expected result aligned with the acceptance criteria>"
  {', "notes": "<refinement note>"' if include_notes else ''}
}}"""

        raw = call_groq(client, prompt, temperature=0.2, max_tokens=700)
        if not raw:
            print(f"  ERROR: No response for {test_id}.")
            continue

        test = extract_json_block(raw)
        if not test:
            print(f"  ERROR: Could not parse JSON for {test_id}.")
            print(f"  Raw (first 300 chars): {raw[:300]}")
            test = build_fallback_test(req, test_id, include_notes)

        # Enforce required keys
        test.setdefault("test_id", test_id)
        test.setdefault("requirement_id", req["id"])
        test.setdefault("scenario", req["description"][:120] if req["description"] else f"Test for {req['id']}")
        test.setdefault("steps", ["Open the app", "Perform the action", "Verify the result"])
        test.setdefault("expected_result", req["acceptance"][:200] if req["acceptance"] else req["description"][:200])

        test["test_id"] = str(test["test_id"])
        test["requirement_id"] = req["id"]
        test["scenario"] = str(test["scenario"]).strip()
        if not isinstance(test.get("steps"), list):
            test["steps"] = [str(test.get("steps"))]
        test["steps"] = [str(step).strip() for step in test["steps"] if str(step).strip()]
        if len(test["steps"]) < 2:
            test["steps"] = build_fallback_test(req, test_id, include_notes)["steps"]
        test["expected_result"] = str(test["expected_result"]).strip()
        if include_notes and not test.get("notes"):
            test["notes"] = "Generated to satisfy the required test scenario format."

        all_tests.append(test)
        time.sleep(0.4)   # polite pacing

    if all_tests:
        save_tests(all_tests, output_path)
        validate_tests(all_tests, pipeline_label, valid_requirement_ids)
    else:
        print(f"  ERROR: No tests generated for {pipeline_label}.")


