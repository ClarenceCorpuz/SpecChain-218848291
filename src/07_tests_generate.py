def handle_manual_tests():
    print("\n[MANUAL] Checking tests_manual.json …")

    if os.path.exists(TESTS_MANUAL):
        with open(TESTS_MANUAL, "r", encoding="utf-8") as f:
            data = json.load(f)
        tests = data.get("tests", [])
        print(f"  Found {len(tests)} existing manual test(s).")
        validate_tests(tests, "manual")
        return

    # Build a starter template from manual spec
    reqs = parse_requirements_from_spec(SPEC_MANUAL)
    if not reqs:
        reqs = [{
            "id": "FR1",
            "description": "PLACEHOLDER requirement description",
            "acceptance":  "PLACEHOLDER acceptance criteria",
            "persona":     "PLACEHOLDER persona",
            "notes":       "",
        }]

    tests = []
    for i, req in enumerate(reqs, start=1):
        tests.append({
            "test_id":        f"T_manual_{i}",
            "requirement_id": req["id"],
            "scenario":       f"PLACEHOLDER: Describe the test scenario for {req['id']}",
            "steps": [
                "PLACEHOLDER: Step 1 — describe the precondition / setup",
                "PLACEHOLDER: Step 2 — describe the user action",
                "PLACEHOLDER: Step 3 — describe what to verify",
            ],
            "expected_result": (
                f"PLACEHOLDER: {req['acceptance'][:120]}"
                if req["acceptance"] else "PLACEHOLDER: Expected outcome"
            ),
        })

    save_tests(tests, TESTS_MANUAL)
    print("  ✏️   Edit tests_manual.json to replace all PLACEHOLDER values.")


