def call_groq(client, prompt, temperature=0.3, max_tokens=2048):
    for attempt in range(MAX_RETRIES):
        try:
            response = client.chat.completions.create(
                model=MODEL,
                messages=[{"role": "user", "content": prompt}],
                temperature=temperature,
                max_tokens=max_tokens,
            )
            return response.choices[0].message.content
        except Exception as e:
            wait = 2 ** attempt
            print(f"  ⚠️  Groq error (attempt {attempt+1}/{MAX_RETRIES}): {e}")
            if attempt < MAX_RETRIES - 1:
                time.sleep(wait)
    return None


def extract_json_block(text):
    """Return the first JSON object or array found in a string."""
    # Try object first
    match = re.search(r"\{[\s\S]*\}", text)
    if match:
        try:
            return json.loads(match.group())
        except json.JSONDecodeError:
            pass
    # Try array
    match = re.search(r"\[[\s\S]*\]", text)
    if match:
        try:
            return json.loads(match.group())
        except json.JSONDecodeError:
            pass
    return None


def parse_requirements_from_spec(spec_path):
    """Parse requirement blocks from a spec .md file."""
    if not os.path.exists(spec_path):
        return []

    with open(spec_path, "r", encoding="utf-8") as f:
        content = f.read()

    reqs = []
    # Split on separator lines
    blocks = re.split(r"─{10,}", content)
    for block in blocks:
        rid_match     = re.search(r"Requirement ID:\s*(.+)", block)
        desc_match    = re.search(r"Description:\s*\[(.+?)\]", block, re.DOTALL)
        ac_match      = re.search(r"Acceptance Criteria:\s*\[(.+?)\]", block, re.DOTALL)
        persona_match = re.search(r"Source Persona:\s*\[(.+?)\]", block)
        notes_match   = re.search(r"Notes:\s*\[(.+?)\]", block, re.DOTALL)

        if rid_match:
            reqs.append({
                "id":          rid_match.group(1).strip(),
                "description": desc_match.group(1).strip()   if desc_match    else "",
                "acceptance":  ac_match.group(1).strip()     if ac_match      else "",
                "persona":     persona_match.group(1).strip() if persona_match else "",
                "notes":       notes_match.group(1).strip()  if notes_match   else "",
            })

    if reqs:
        return reqs

    current_persona = ""
    for line in content.splitlines():
        stripped = line.strip()
        section_match = SECTION_PERSONA_RE.match(stripped)
        if section_match:
            current_persona = section_match.group(2).strip()
            continue

        table_match = TABLE_REQ_RE.match(stripped)
        if not table_match:
            continue

        requirement_id, requirement_type, priority, description, derived_from = table_match.groups()
        if requirement_id == "Req ID":
            continue
        if set(requirement_id) == {"-"}:
            continue

        reqs.append({
            "id": requirement_id.strip(),
            "description": description.strip(),
            "acceptance": "",
            "persona": current_persona,
            "notes": f"{requirement_type.strip()} | {priority.strip()} | {derived_from.strip()}",
        })

    return reqs


def save_tests(tests, path):
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"tests": tests}, f, indent=2)
    print(f"  ✅  Tests saved → {path}  ({len(tests)} test case(s))")


def validate_tests(tests, label, valid_requirement_ids=None):
    errors = []
    seen_ids = set()
    for t in tests:
        tid = t.get("test_id", "?")
        if not t.get("test_id"):
            errors.append("missing test_id")
        elif tid in seen_ids:
            errors.append(f"{tid}: duplicate test_id")
        else:
            seen_ids.add(tid)

        if not t.get("requirement_id"):
            errors.append(f"{tid}: missing requirement_id")
        elif valid_requirement_ids is not None and t.get("requirement_id") not in valid_requirement_ids:
            errors.append(f"{tid}: requirement_id '{t.get('requirement_id')}' not found in spec")
        if not t.get("scenario"):
            errors.append(f"{tid}: missing scenario")
        elif not isinstance(t.get("scenario"), str):
            errors.append(f"{tid}: scenario must be a string")

        steps = t.get("steps", [])
        if not isinstance(steps, list):
            errors.append(f"{tid}: steps must be a list")
        elif len(steps) < 2:
            errors.append(f"{tid}: fewer than 2 steps")
        elif any(not isinstance(step, str) or not step.strip() for step in steps):
            errors.append(f"{tid}: steps must contain non-empty strings")

        if not t.get("expected_result"):
            errors.append(f"{tid}: missing expected_result")
        elif not isinstance(t.get("expected_result"), str):
            errors.append(f"{tid}: expected_result must be a string")

    if errors:
        print(f"  ⚠️  [{label}] {len(errors)} issue(s):")
        for e in errors:
            print(f"       - {e}")
    else:
        print(f"  ✅  [{label}] All {len(tests)} tests valid.")
    return errors


def build_fallback_test(req, test_id, include_notes=False):
    scenario = req["description"].replace("The system shall ", "", 1).strip()
    if not scenario:
        scenario = f"Validate requirement {req['id']}"
    test = {
        "test_id": test_id,
        "requirement_id": req["id"],
        "scenario": scenario[:120],
        "steps": [
            f"Review the requirement context for {req['id']}.",
            "Perform the user action or system condition described by the requirement.",
            "Observe the system behavior and record the outcome.",
        ],
        "expected_result": req["acceptance"] or req["description"],
    }
    if include_notes:
        test["notes"] = "Generated from the current requirement text because no valid stored test matched the spec."
    return test


